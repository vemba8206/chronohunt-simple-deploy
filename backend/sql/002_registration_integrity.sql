-- Focused final PIN/registration policy AFTER inspecting the already-applied 001 migration.
-- Version 3 supersedes the unapplied version-2 draft. PIN correctness is NOT verified.
-- No tables/columns are added, no existing timestamps/rankings are reset.
begin;

create or replace function public.ch_integrity_status() returns jsonb
language sql security invoker set search_path = '' as $$
  select jsonb_build_object('registration_integrity',3)
$$;
revoke all on function public.ch_integrity_status() from public, anon, authenticated;
grant execute on function public.ch_integrity_status() to service_role;

comment on column public.teams.tinkercad_timestamp is
  'Legacy column name: authoritative WEBSITE submission acceptance time generated by the database. Not an independently observed Tinkercad event.';

create or replace function public.ch_sync(p_rows jsonb) returns jsonb
language plpgsql security invoker set search_path = '' as $$
declare s public.competition_settings%rowtype; n integer;
begin
  select * into strict s from public.competition_settings where id=1 for update;
  if s.finalized_at is not null then
    return jsonb_build_object('count',0,'skipped',true,'message','Finalized results are immutable.');
  end if;
  if jsonb_typeof(p_rows) <> 'array' then raise exception 'Expected source array'; end if;
  if exists (select 1 from jsonb_array_elements(p_rows) r
    where r->>'team_id' is null or r->>'team_id' !~ '^[A-Z0-9][A-Z0-9_-]{0,31}$'
      or r->>'form_timestamp' is null
      or r->>'form_timestamp' !~ '(Z|[+-][0-9]{2}:[0-9]{2})$') then
    raise exception 'Invalid source identifiers/timestamps';
  end if;
  if exists (select 1 from jsonb_array_elements(p_rows) r
    group by r->>'team_id' having count(*) > 1) then raise exception 'Duplicate source identifiers'; end if;
  -- Never overwrite an established original registration timestamp.
  -- A source edit must be corrected/reviewed, not silently reorder candidates.
  if exists (select 1 from jsonb_array_elements(p_rows) r
    join public.teams t on t.team_id=r->>'team_id'
    where t.form_timestamp is not null
      and t.form_timestamp <> (r->>'form_timestamp')::timestamptz) then
    return jsonb_build_object('error','registration_timestamp_conflict');
  end if;
  update public.teams set source_present=false where source_present;
  insert into public.teams (id, team_id, form_timestamp, source_present, created_at, updated_at)
  select gen_random_uuid(), r->>'team_id', (r->>'form_timestamp')::timestamptz, true, clock_timestamp(), clock_timestamp()
    from jsonb_array_elements(p_rows) r
  on conflict (team_id) do update set form_timestamp=coalesce(public.teams.form_timestamp,excluded.form_timestamp),
    source_present=true, updated_at=excluded.updated_at;
  n := jsonb_array_length(p_rows);
  update public.competition_settings set last_synced_at=clock_timestamp(), updated_at=clock_timestamp() where id=1;
  insert into public.ch_audit(event,details) values ('sheet_sync',jsonb_build_object('count',n));
  return jsonb_build_object('count',n,'skipped',false);
end $$;

-- ch_finalize must propagate a rejected sync, then preserve its existing ordering.
create or replace function public.ch_finalize(p_rows jsonb) returns jsonb
language plpgsql security invoker set search_path = '' as $$
declare s public.competition_settings%rowtype; valid_count integer; selected_count integer; sync_result jsonb;
begin
  select * into strict s from public.competition_settings where id=1 for update;
  if s.tinkercad_status <> 'ENDED' then return jsonb_build_object('error','round_active'); end if;
  if s.finalized_at is not null then
    return jsonb_build_object('status','ENDED','finalized',true,'already_finalized',true);
  end if;
  sync_result := public.ch_sync(p_rows);
  if sync_result ? 'error' then return sync_result; end if;
  select count(*) into valid_count from public.teams
    where source_present and form_timestamp is not null and tinkercad_valid is true and tinkercad_timestamp < s.tinkercad_end_time;
  update public.teams set qualified=false, rank=null;
  with candidates as (
    select id, team_id, 0 as priority, form_timestamp as ordering_time
    from public.teams where source_present and form_timestamp is not null and tinkercad_valid is true and tinkercad_timestamp < s.tinkercad_end_time
    union all
    select id, team_id, 1 as priority, form_timestamp as ordering_time
    from public.teams where source_present and coalesce(tinkercad_valid,false)=false and form_timestamp is not null
  ), ordered as (
    select id, row_number() over (order by priority, ordering_time, team_id collate "C", id) as position
    from candidates
  )
  update public.teams t set qualified=true, rank=o.position::integer, updated_at=clock_timestamp()
    from ordered o where t.id=o.id and o.position <= s.qualification_slots;
  get diagnostics selected_count = row_count;
  update public.competition_settings set finalized_at=clock_timestamp(), updated_at=clock_timestamp() where id=1;
  insert into public.ch_audit(event,details) values ('round_finalized',
    jsonb_build_object('qualified',selected_count,'valid',valid_count,'slots',s.qualification_slots));
  return jsonb_build_object('status','ENDED','finalized',true,'qualified',selected_count,
    'warning',case when valid_count > s.qualification_slots then
      'Accepted submissions exceed qualification slots; earliest Form registrations qualify.' else null end);
end $$;

create or replace function public.ch_team(p_team_id text) returns jsonb
language sql security invoker set search_path = '' as $$
  select jsonb_build_object('tinkercad_valid', coalesce(tinkercad_valid, false))
  from public.teams where team_id=upper(btrim(p_team_id)) and source_present and form_timestamp is not null
$$;

create or replace function public.ch_submit(p_team_id text, p_code text) returns jsonb
language plpgsql security invoker set search_path = '' as $$
declare s public.competition_settings%rowtype; t public.teams%rowtype; accepted timestamptz;
begin
  select * into strict s from public.competition_settings where id=1 for update;
  if s.tinkercad_status <> 'ACTIVE' then return jsonb_build_object('error','round_closed'); end if;
  select * into t from public.teams where team_id=upper(btrim(p_team_id)) and source_present
    and form_timestamp is not null for update;
  if not found then return jsonb_build_object('error','unknown_team'); end if;
  if coalesce(t.tinkercad_valid,false) then return jsonb_build_object('error','duplicate_submission'); end if;
  if p_code is null or length(btrim(p_code)) not between 1 and 256 then
    return jsonb_build_object('error','invalid_code');
  end if;
  accepted := clock_timestamp();
  update public.teams set tinkercad_code=p_code, tinkercad_timestamp=accepted,
    tinkercad_valid=true, updated_at=accepted where id=t.id;
  return jsonb_build_object('accepted',true);
end $$;

-- Legacy column names are retained; valid means accepted website submission, not PIN correctness.
comment on column public.teams.tinkercad_valid is 'Accepted registered website submission; does not certify circuit PIN correctness.';
comment on column public.teams.tinkercad_code is 'Submitted circuit PIN, restricted to backend/database owners. Never returned by team or leaderboard RPCs.';

create or replace function public.ch_leaderboard() returns jsonb
language sql security invoker set search_path = '' as $$
  select coalesce(jsonb_agg(jsonb_build_object('rank',position,'team_id',team_id) order by position),'[]'::jsonb)
  from (
    select t.team_id, t.rank::bigint as position from public.teams t, public.competition_settings s
      where s.id=1 and s.finalized_at is not null and t.qualified is true
    union all
    select t.team_id, row_number() over (order by t.form_timestamp, t.team_id collate "C", t.id) as position
      from public.teams t, public.competition_settings s
      where s.id=1 and s.finalized_at is null and t.tinkercad_valid is true
        and t.source_present and t.form_timestamp is not null
        and (s.tinkercad_status='ACTIVE' or t.tinkercad_timestamp < s.tinkercad_end_time)
  ) positions
$$;

revoke all on function public.ch_sync(jsonb), public.ch_finalize(jsonb), public.ch_team(text),
  public.ch_submit(text,text), public.ch_leaderboard() from public, anon, authenticated;
grant execute on function public.ch_sync(jsonb), public.ch_finalize(jsonb), public.ch_team(text),
  public.ch_submit(text,text), public.ch_leaderboard() to service_role;
commit;
